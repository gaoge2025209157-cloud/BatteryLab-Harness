"""Ground-truth evaluation for Phase 2 scientific correctness.

Reference values are external data, not values regenerated by the implementation
under test. Numeric checks report whether calculated values match those
references; human knowledge review remains a separate per-claim workflow.
"""

import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Dict, Mapping, Optional, Tuple

from .scientific_standard import (
    SCIENTIFIC_STANDARD_VERSION,
    scientific_standard_hash,
)


@dataclass(frozen=True)
class ExpectedValue:
    value: float
    absolute_tolerance: Optional[float] = None
    relative_tolerance: Optional[float] = None

    @classmethod
    def from_dict(cls, payload: Mapping[str, Any]) -> "ExpectedValue":
        absolute = payload.get("absolute_tolerance")
        relative = payload.get("relative_tolerance")
        if absolute is not None and float(absolute) < 0:
            raise ValueError("absolute tolerance must be nonnegative")
        if relative is not None and float(relative) < 0:
            raise ValueError("relative tolerance must be nonnegative")
        return cls(
            value=float(payload["value"]),
            absolute_tolerance=None if absolute is None else float(absolute),
            relative_tolerance=None if relative is None else float(relative),
        )

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class GroundTruthCase:
    case_id: str
    description: str
    expected: Mapping[str, ExpectedValue]
    input_file: str = ""
    input_mode: str = ""
    parameters: Mapping[str, Any] = None

    def to_dict(self) -> dict:
        payload = {
            "case_id": self.case_id,
            "description": self.description,
            "expected": {key: value.to_dict() for key, value in self.expected.items()},
        }
        if self.input_file:
            payload["input_file"] = self.input_file
        if self.input_mode:
            payload["input_mode"] = self.input_mode
        if self.parameters:
            payload["parameters"] = dict(self.parameters)
        return payload


@dataclass(frozen=True)
class GroundTruthSuite:
    suite_id: str
    standard_version: str
    standard_hash: str
    cases: Tuple[GroundTruthCase, ...]

    @classmethod
    def from_dict(cls, payload: Mapping[str, Any]) -> "GroundTruthSuite":
        version = str(payload["standard_version"])
        digest = str(payload["standard_hash"])
        if version != SCIENTIFIC_STANDARD_VERSION:
            raise ValueError("ground-truth suite uses an unsupported standard version")
        if digest != scientific_standard_hash():
            raise ValueError("ground-truth suite standard hash does not match the frozen standard hash")
        cases = []
        seen = set()
        for item in payload.get("cases", ()):
            case_id = str(item["case_id"])
            if not case_id or case_id in seen:
                raise ValueError("ground-truth case ids must be nonempty and unique")
            seen.add(case_id)
            expected = {
                str(key): ExpectedValue.from_dict(value)
                for key, value in item.get("expected", {}).items()
            }
            if not expected:
                raise ValueError("each ground-truth case requires expected values")
            parameters = item.get("parameters", {})
            if not isinstance(parameters, Mapping):
                raise ValueError("ground-truth case parameters must be a mapping")
            cases.append(
                GroundTruthCase(
                    case_id,
                    str(item.get("description", "")),
                    expected,
                    str(item.get("input_file", "")),
                    str(item.get("input_mode", "")),
                    dict(parameters),
                )
            )
        if not cases:
            raise ValueError("ground-truth suite requires at least one case")
        return cls(
            suite_id=str(payload["suite_id"]),
            standard_version=version,
            standard_hash=digest,
            cases=tuple(cases),
        )

    def to_dict(self) -> dict:
        return {
            "suite_id": self.suite_id,
            "standard_version": self.standard_version,
            "standard_hash": self.standard_hash,
            "cases": [case.to_dict() for case in self.cases],
        }


@dataclass(frozen=True)
class MetricCheck:
    metric_path: str
    expected: float
    actual: Optional[float]
    delta: Optional[float]
    allowed_delta: float
    tolerance_kind: str
    passed: bool
    message: str

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class CaseResult:
    case_id: str
    passed: bool
    checks: Tuple[MetricCheck, ...]

    def to_dict(self) -> dict:
        return {
            "case_id": self.case_id,
            "passed": self.passed,
            "checks": [check.to_dict() for check in self.checks],
        }


@dataclass(frozen=True)
class GroundTruthResult:
    suite_id: str
    standard_version: str
    standard_hash: str
    numeric_passed: bool
    total_checks: int
    passed_checks: int
    case_results: Tuple[CaseResult, ...]

    def to_dict(self) -> dict:
        return {
            "suite_id": self.suite_id,
            "standard_version": self.standard_version,
            "standard_hash": self.standard_hash,
            "numeric_passed": self.numeric_passed,
            "reference_checks_passed": reference_checks_passed(self),
            "total_checks": self.total_checks,
            "passed_checks": self.passed_checks,
            "case_results": [result.to_dict() for result in self.case_results],
        }


def _value_at(payload: Mapping[str, Any], path: str) -> Optional[float]:
    current: Any = payload
    for part in path.split("."):
        if not isinstance(current, Mapping) or part not in current:
            return None
        current = current[part]
    try:
        return float(current)
    except (TypeError, ValueError):
        return None


def _check(path: str, expected: ExpectedValue, actual: Optional[float]) -> MetricCheck:
    if expected.absolute_tolerance is not None:
        allowed = expected.absolute_tolerance
        kind = "absolute"
    elif expected.relative_tolerance is not None:
        allowed = abs(expected.value) * expected.relative_tolerance
        kind = "relative"
    else:
        allowed = 0.0
        kind = "exact"
    if actual is None:
        return MetricCheck(path, expected.value, None, None, allowed, kind, False, "missing or nonnumeric actual value")
    delta = abs(actual - expected.value)
    passed = delta <= allowed + 1e-15
    return MetricCheck(
        path,
        expected.value,
        actual,
        delta,
        allowed,
        kind,
        passed,
        "within tolerance" if passed else "outside tolerance",
    )


def evaluate_ground_truth(
    suite: GroundTruthSuite,
    actual_by_case: Mapping[str, Mapping[str, Any]],
) -> GroundTruthResult:
    case_results = []
    for case in suite.cases:
        actual = actual_by_case.get(case.case_id, {})
        checks = tuple(
            _check(path, expected, _value_at(actual, path))
            for path, expected in case.expected.items()
        )
        case_results.append(CaseResult(case.case_id, all(item.passed for item in checks), checks))
    total = sum(len(case.checks) for case in case_results)
    passed = sum(check.passed for case in case_results for check in case.checks)
    return GroundTruthResult(
        suite.suite_id,
        suite.standard_version,
        suite.standard_hash,
        bool(case_results) and all(case.passed for case in case_results),
        total,
        passed,
        tuple(case_results),
    )


def load_ground_truth_suite(path: Path) -> GroundTruthSuite:
    source = Path(path)
    payload = json.loads(source.read_text(encoding="utf-8-sig"))
    if not isinstance(payload, Mapping):
        raise ValueError("ground-truth suite root must be a JSON object")
    return GroundTruthSuite.from_dict(payload)


def _actual_for_case(case: GroundTruthCase, root: Path) -> Mapping[str, Any]:
    if not case.input_file or not case.input_mode:
        raise ValueError("ground-truth case {} has no executable input".format(case.case_id))
    source = (root / case.input_file).resolve()
    try:
        source.relative_to(root.resolve())
    except ValueError as error:
        raise ValueError("ground-truth input must remain inside the standards directory") from error
    if not source.is_file():
        raise ValueError("ground-truth input is missing: {}".format(case.input_file))

    if case.input_mode == "raw_current":
        from .analysis import analyze_cycles, load_cycling_csv

        active_mass = case.parameters.get("active_mass_mg") if case.parameters else None
        metrics = analyze_cycles(load_cycling_csv(source), active_mass_mg=active_mass)
        return {"cycle_{}".format(item.cycle): item.to_dict() for item in metrics}
    if case.input_mode == "specific_capacity_curve":
        from .land_curve import analyze_land_capacity_curve

        payload = analyze_land_capacity_curve(source)
        return {
            "cycle_{}".format(item["cycle"]): dict(item)
            for item in payload["report"].get("cycles", ())
        }
    raise ValueError("unsupported ground-truth input_mode: {}".format(case.input_mode))


def run_ground_truth_suite(path: Path) -> GroundTruthResult:
    source = Path(path).resolve()
    suite = load_ground_truth_suite(source)
    actual = {
        case.case_id: _actual_for_case(case, source.parent)
        for case in suite.cases
    }
    return evaluate_ground_truth(suite, actual)


def reference_checks_passed(result: GroundTruthResult) -> bool:
    """Return whether every frozen reference-value check passed."""

    return result.numeric_passed
